#!/usr/bin/env python3
"""Writes tokens/tokens.json, tokens/dark.toml and tokens/light.toml from the Malva UI kit.

The kit (github.com/Malvaos/Malva-ui-toolkit) owns the design tokens: `tokens/malva-tokens.json` is the one file a
person edits, and `dist/resolved.json` holds every colour role resolved to hex for light and dark. This repo keeps
copies of those values in the shapes that design tools and a Rust or Flutter theme read, so the two cannot disagree.
Nothing in tokens/ is edited by hand.

    python3 tools/sync_tokens.py [--kit PATH]            write
    python3 tools/sync_tokens.py [--kit PATH] --check    exit 1 if tokens/ differs from the kit, 2 if the kit is not found

PATH is a checkout of the kit; by default ../Malva-ui-toolkit or ../malva-ui-kit next to this repo, or $MALVA_KIT."""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(ROOT, "tokens")


def find_kit():
    args = sys.argv[1:]
    cands = []
    if "--kit" in args:
        cands.append(args[args.index("--kit") + 1])
    if os.environ.get("MALVA_KIT"):
        cands.append(os.environ["MALVA_KIT"])
    cands += [os.path.join(ROOT, "..", "Malva-ui-toolkit"), os.path.join(ROOT, "..", "malva-ui-kit")]
    for c in cands:
        if os.path.isfile(os.path.join(c, "tokens", "malva-tokens.json")) and os.path.isfile(os.path.join(c, "dist", "resolved.json")):
            return os.path.normpath(c)
    return None


def hexv(s):
    """'#F5F5F7FF' -> '#F5F5F7' (opaque colours drop the alpha byte), '#F5F5F7B8' stays."""
    s = s.upper()
    return s[:7] if len(s) == 9 and s.endswith("FF") else s


def fl(n):
    return f"{float(n):.1f}"


def build(kit):
    src_path = os.path.join(kit, "tokens", "malva-tokens.json")
    raw = open(src_path, "rb").read()
    tok = json.loads(raw)
    res = json.load(open(os.path.join(kit, "dist", "resolved.json")))
    sha = hashlib.sha256(raw).hexdigest()
    colors = {m: {k: hexv(v) for k, v in res[m].items()} for m in ("light", "dark")}
    brand = {k: v.upper() for k, v in res["brand"].items()}
    data = {
        "$comment": "GENERATED by tools/sync_tokens.py from the Malva UI kit (tokens/malva-tokens.json). Do not edit by hand.",
        "source": {"repository": "Malvaos/Malva-ui-toolkit", "file": "tokens/malva-tokens.json", "sha256": sha},
        "light": colors["light"], "dark": colors["dark"], "brand": brand,
        "radius": tok["radius"], "space": tok["space"], "size": tok["size"], "type": tok["type"],
        "motion": tok["motion"], "elevation": tok["elevation"],
    }
    files = {"tokens.json": json.dumps(data, indent=2, ensure_ascii=False) + "\n"}
    for mode in ("dark", "light"):
        c = colors[mode]
        L = [f"# GENERATED by tools/sync_tokens.py from the Malva UI kit (sha256 {sha[:12]}). Do not edit by hand.",
             f'name = "Malva {mode.capitalize()}"', f"is_dark = {'true' if mode == 'dark' else 'false'}",
             f"accent_seed_hex = 0x{c['accent'][1:7]}", "",
             "[spacing]"] + [f"{k} = {fl(v)}" for k, v in tok["space"].items()] + ["", "[radii]"] + \
            [f"{k} = {fl(v)}" for k, v in tok["radius"].items()] + ["", "[sizes]"] + \
            [f"{k.replace('-', '_')} = {fl(v)}" for k, v in tok["size"].items()] + ["", "[typography]",
             f'font_family_sans = "{tok["type"]["family"]["ui"]}"', f'font_family_mono = "{tok["type"]["family"]["mono"]}"']
        for role, s in tok["type"]["scale"].items():
            L += ["", f"[typography.{role.replace('-', '_')}]", f"size = {fl(s['size'])}", f"weight = {s['weight']}", f"line = {fl(s['line'])}"]
        L += ["", "[motion]"] + [f"{k}_ms = {v}" for k, v in tok["motion"]["duration"].items()]
        L += ["", "[motion.easing]"] + [f"{k.replace('-', '_')} = [{', '.join(str(x) for x in v)}]" for k, v in tok["motion"]["easing"].items()]
        sp = tok["motion"]["spring"]
        L += ["", "[motion.spring]", f"stiffness = {fl(sp['stiffness'])}", f"damping = {fl(sp['damping'])}", f"mass = {fl(sp['mass'])}"]
        for lvl, e in tok["elevation"].items():
            L += ["", f"[elevation.level{lvl}]", f"y = {fl(e['y'])}", f"blur = {fl(e['blur'])}", f"alpha = {e['alpha-' + mode]}"]
        L += ["", "[colors]"] + [f'{k.replace("-", "_")} = "{v}"' for k, v in c.items()]
        L += ["", "[brand]"] + [f'{k} = "{v}"' for k, v in brand.items()]
        files[f"{mode}.toml"] = "\n".join(L) + "\n"
    return files


def main():
    kit = find_kit()
    if not kit:
        print("sync_tokens: kit not found; pass --kit PATH (a checkout of Malvaos/Malva-ui-toolkit)")
        return 2
    files = build(kit)
    if "--check" in sys.argv:
        stale = [n for n, t in files.items() if not os.path.exists(os.path.join(OUT, n)) or open(os.path.join(OUT, n)).read() != t]
        if stale:
            print("sync_tokens: out of date:", ", ".join(stale))
            return 1
        print("sync_tokens: tokens/ matches the kit at", kit)
        return 0
    os.makedirs(OUT, exist_ok=True)
    for n, t in files.items():
        open(os.path.join(OUT, n), "w").write(t)
    print("tokens/ written from", kit, "->", ", ".join(files))
    return 0


sys.exit(main())
